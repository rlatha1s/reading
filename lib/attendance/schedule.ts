export const SCHEDULE_VERSION = '2026-chuseok';
export const READING_HOLIDAYS = ['2026-09-24', '2026-09-25'];

// Original dates are stable storage keys for each reading, including existing records.
// Rescheduling changes calendar dates, never the identity of a reading or its records.
export const READING_SCHEDULE = ORIGINAL_READING_SCHEDULE.map(entry => {
 const cursor = new Date(`${entry.date}T00:00:00Z`);
 if (entry.date >= '2026-09-24') {
  let remaining = 2;
  while (remaining) {
   cursor.setUTCDate(cursor.getUTCDate() + 1);
   if (![0, 6].includes(cursor.getUTCDay())) remaining--;
  }
 }
 const date = cursor.toISOString().slice(0, 10);
 const weekday = '일월화수목금토'[cursor.getUTCDay()];
 return { date, storageDate: entry.date, reading: entry.reading,
  label: `[${date.replaceAll('-', '. ')} (${weekday})] ${entry.reading}` };
});
export function storageDateFor(date: string) {
 return READING_SCHEDULE.find(entry => entry.date === date)?.storageDate;
}
export function calendarDateFor(storageDate: string) {
 return READING_SCHEDULE.find(entry => entry.storageDate === storageDate)?.date ?? storageDate;
}
export function calendarRecord<T extends { date: string }>(record: T): T {
 return { ...record, date: calendarDateFor(record.date) };
}
